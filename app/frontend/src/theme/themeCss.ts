import { cssVariables, DARK, LIGHT, staticVariables, type ThemeTokens } from './tokens.ts'

function declarations(tokens: ThemeTokens, indent: string, colorScheme: string): string {
  const lines = [`${indent}color-scheme: ${colorScheme};`]
  for (const [name, value] of Object.entries(cssVariables(tokens))) {
    lines.push(`${indent}${name}: ${value};`)
  }
  return lines.join('\n')
}

function staticDeclarations(): string {
  return Object.entries(staticVariables())
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')
}

/** The generated body of `theme.css`: shared tokens, then light by default, dark by system preference or by `data-theme`. */
export function renderThemeCss(): string {
  return [
    '/* Generated by `npm run theme:css` from src/theme/tokens.ts. Do not edit. */',
    ':root {',
    staticDeclarations(),
    '}',
    '',
    ':root {',
    declarations(LIGHT, '  ', 'light'),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root:where(:not([data-theme="light"])) {',
    declarations(DARK, '    ', 'dark'),
    '  }',
    '}',
    '',
    ':root[data-theme="dark"] {',
    declarations(DARK, '  ', 'dark'),
    '}',
    '',
  ].join('\n')
}
