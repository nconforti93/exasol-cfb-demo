"""The data dictionary of `CFB_MODEL`: `docs/model-dictionary.md`, generated from `sql/model/`.

`make model-docs` writes it; `tests/unit/test_model_dictionary.py` fails when the committed file
differs from `render_dictionary()`. One section per object in file order with its grain (the first
sentence of the object comment), the full comment, the objects it reads, and each column with its
comment. It needs no database: the comments in the files are the comments the deploy installs and
reads back (`vs/host/sqlobjects.py`), rendered for the real namespace.
"""

from __future__ import annotations

import re
from collections.abc import Callable, Iterable
from pathlib import Path

from model.deploy import MODEL_DIR, ROOT, prepare
from vs.host.namespace import Namespace
from vs.host.sqlobjects import SqlObject

DICTIONARY_PATH = ROOT / "docs" / "model-dictionary.md"
SQL_DIRECTORY = "sql/model"
_KIND_WORDS = {"TABLE": "table", "VIEW": "view", "FUNCTION": "function", "SCRIPT": "script"}
_SENTENCE_END = re.compile(r"\.(?:\s|$)")
_SIGNATURE = re.compile(
    r"CREATE\s+OR\s+REPLACE\s+FUNCTION\s+(?:\S+\.)?(?P<signature>.*?)\s+IS\b", re.DOTALL
)
_HEADER = (
    "# CFB_MODEL data dictionary\n"
    "\n"
    f"Generated by `make model-docs` from `{SQL_DIRECTORY}/`; do not edit. The comments below "
    "are the ones stored in the database (`EXA_ALL_OBJECTS`, `EXA_ALL_COLUMNS`), which the "
    "deploy reads back and compares. Names are unquoted upper case: no quoting is ever needed.\n"
    "\n"
    'Every table and view comment starts with its grain, "One row per ...". '
    "`Reads` lists the objects a view or table selects from, in schemas `CFB_MODEL`, `CFB_CORE` "
    "and `CFB_META` (the loader's plan views). The model never reads the virtual schema.\n"
    "\n"
    "A *derived table* is a materialized view (decision [40]): the deploy fills it, and "
    "`CFB_INFRA.REFRESH_MODEL` rebuilds it after every load (refresh step 100, and the post-hook "
    "of `make backfill` and `make restore`), so its rows are current as of the last load. The "
    "other tables are curated seeds.\n"
)


def render_dictionary(directory: Path = MODEL_DIR) -> str:
    """The dictionary text of the model files in `directory`, linted and rendered for the real
    namespace; raises `ModelLintError` or `DeployError` like a deploy."""
    return generate(prepare(Namespace(""), directory))


def generate(
    objects: Iterable[SqlObject],
    *,
    title: str = "CFB_MODEL",
    intro: str | None = None,
    source_path: Callable[[SqlObject], str] | None = None,
) -> str:
    """The dictionary text of rendered objects, in file order, with a caller's heading and paths."""
    items = list(objects)
    header = _HEADER if intro is None else f"# {title} data dictionary\n\n{intro.strip()}\n"
    path = source_path or (lambda item: f"{SQL_DIRECTORY}/{item.file}")
    parts = [header, _overview(items)]
    parts.extend(_section(item, path(item)) for item in items)
    return "\n".join(parts).rstrip("\n") + "\n"


def write_dictionary(path: Path = DICTIONARY_PATH, directory: Path = MODEL_DIR) -> int:
    """Write the dictionary to `path`; returns the number of objects documented."""
    text = render_dictionary(directory)
    path.write_text(text, encoding="utf-8")
    return text.count("\n## ") - 1


def grain(comment: str | None) -> str:
    """The first sentence of an object comment, without its final period."""
    if not comment:
        return ""
    end = _SENTENCE_END.search(comment)
    first = comment[: end.start()] if end else comment
    return _cell(first)


def _overview(items: list[SqlObject]) -> str:
    rows = [
        f"| `{item.name}` | {_kind(item)} | `{item.file}` | {grain(item.comment)} |"
        for item in items
    ]
    return "\n".join(
        ["## Objects", "", "| Object | Kind | File | Grain |", "|---|---|---|---|", *rows, ""]
    )


def _section(item: SqlObject, source_path: str) -> str:
    lines = [
        f"## {item.name}",
        "",
        f"*{_kind(item).capitalize()}, `{source_path}`.*",
        "",
        (item.comment or "").strip(),
        "",
    ]
    signature = _signature(item)
    if signature:
        lines += [f"Signature: `{signature}`", ""]
    if item.references:
        lines += ["Reads: " + ", ".join(f"`{reference}`" for reference in item.references), ""]
    if item.columns:
        lines += ["| Column | Comment |", "|---|---|"]
        lines += [f"| `{column.name}` | {_cell(column.comment or '')} |" for column in item.columns]
        lines.append("")
    return "\n".join(lines)


def _kind(item: SqlObject) -> str:
    if item.kind == "TABLE" and item.references:
        return "derived table"
    return _KIND_WORDS[item.kind]


def _signature(item: SqlObject) -> str:
    if item.kind != "FUNCTION":
        return ""
    match = _SIGNATURE.search(item.statements[0]) if item.statements else None
    return " ".join(match.group("signature").split()) if match else ""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")
