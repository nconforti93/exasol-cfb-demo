"""The model's refresh step `<infra>.REFRESH_MODEL` (task 4.1; decisions [15] and [40]).

The script is `model/lua/refresh_model.lua`, bundled like the loader's scripts
(`loader.bundle.build_entry_script`): the namespace constants plus `MODEL_SCHEMA`, a generated
`DERIVED_TABLES` list, `loader/lua/loadlib.lua`, then the entry file. The model deploy installs it
in the same transaction as the model (`model/deploy.py`); `make bundle` also writes the real
namespace's text to `build/sql/model_refresh_model.sql` for review.

Derived tables (decision [40]) are the model's materialized objects: a `TABLE` file whose `INSERT`
reads other objects (the seeds' `INSERT ... VALUES` reads none). The deploy fills them in its
transaction; `REFRESH_MODEL` empties and refills them in file order, so a table only reads tables
rebuilt before it. Their rows are current as of the last load that was followed by a rebuild:

- `REFRESH_WEEK` runs the step as registered step 100 `MODEL` (`loader/load-plan.yaml`), which
  rebuilds, then evaluates and logs the checks of the refreshed week;
- `make backfill` and `make restore` call `rebuild_after_load` when their run ended (a rebuild
  without checks, `REFRESH_MODEL(NULL, NULL, NULL, NULL)`); so does `make refresh` on a target
  whose `REFRESH_STEPS` does not register the step yet (it arrives with the next `make deploy`);
- `make model` (and `make deploy`) refill them in the deploy;
- `make model-refresh [SEASON=y WEEK=w]` runs the step on its own.

A `BACKFILL` started directly with `EXECUTE SCRIPT`, or a manual change of `CFB_CORE`, leaves the
tables stale until one of these runs.
"""

from __future__ import annotations

import re
import sys
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from loader import bundle as lua_bundle
from vs.bundle import BundleError
from vs.cfbd_vs.sqlrender import qualified_name, string_literal
from vs.host.deploy import DeployError
from vs.host.namespace import Namespace
from vs.host.sqlobjects import SqlObject

ROOT = Path(__file__).resolve().parents[1]
STEP_SOURCE = ROOT / "model" / "lua" / "refresh_model.lua"
STEP_NAME = "REFRESH_MODEL"
STEP_PARAMETERS = ("run_id", "season", "week", "season_type")
BUNDLE_FILE = "model_refresh_model.sql"
RESULT_COLUMNS = ("ITEM_KIND", "ITEM_NAME", "SEVERITY", "ITEM_STATUS", "OBSERVED", "DETAIL")

_INSERT = re.compile(r"INSERT\s+INTO\s", re.IGNORECASE)


def derived_tables(objects: Sequence[SqlObject]) -> list[SqlObject]:
    """The model's materialized tables in file order: tables whose `INSERT` reads other objects."""
    return [obj for obj in objects if obj.kind == "TABLE" and obj.references]


def insert_statement(obj: SqlObject) -> str:
    """The one `INSERT ... SELECT` that fills a derived table."""
    inserts = [statement for statement in obj.statements if _INSERT.match(statement)]
    if len(inserts) != 1:
        raise DeployError(
            f"{obj.file}: derived table {obj.name} needs exactly one INSERT, found {len(inserts)}"
        )
    return inserts[0]


def render_prelude(objects: Sequence[SqlObject]) -> str:
    """The Lua `DERIVED_TABLES` list of rendered objects: `{name = ..., insert = [==[...]==]}`."""
    lines = [
        "-- Generated by model/step.py from sql/model/: the derived tables in file order.",
        "local DERIVED_TABLES = {",
    ]
    for obj in derived_tables(objects):
        sql = insert_statement(obj)
        level = 1
        while f"]{'=' * level}]" in sql:
            level += 1
        equals = "=" * level
        lines.append(f'  {{name = "{obj.name}", insert = [{equals}[{sql}]{equals}]}},')
    lines.append("}")
    return "\n".join(lines) + "\n"


def build_step_script(
    namespace: Namespace, objects: Sequence[SqlObject], source: Path = STEP_SOURCE
) -> str:
    """`CREATE OR REPLACE LUA SCRIPT <infra>.REFRESH_MODEL(...)` for rendered model objects."""
    try:
        return lua_bundle.build_entry_script(
            STEP_NAME,
            STEP_PARAMETERS,
            source,
            namespace,
            extra_names={"MODEL_SCHEMA": namespace.model_schema},
            prelude=render_prelude(objects),
        )
    except BundleError as error:
        raise DeployError(f"{STEP_NAME}: {error}") from None


def step_call(
    namespace: Namespace,
    *,
    run_id: int | None = None,
    season: int | None = None,
    week: int | None = None,
    season_type: str | None = None,
) -> str:
    """`EXECUTE SCRIPT <infra>.REFRESH_MODEL(...)`; all NULL rebuilds the tables without checks."""
    values = ["NULL" if value is None else str(int(value)) for value in (run_id, season, week)]
    values.append("NULL" if season_type is None else string_literal(season_type))
    script = qualified_name(namespace.infra_schema, STEP_NAME)
    return f"EXECUTE SCRIPT {script}({', '.join(values)})"


def step_installed(connection: Any, namespace: Namespace) -> bool:
    """Whether the namespace has `REFRESH_MODEL` (the model was deployed since task 4.1)."""
    rows = connection.execute(
        "SELECT COUNT(*) FROM EXA_ALL_SCRIPTS "
        f"WHERE SCRIPT_SCHEMA = {string_literal(namespace.infra_schema)} "
        f"AND SCRIPT_NAME = {string_literal(STEP_NAME)}"
    ).fetchall()
    return int(rows[0][0]) > 0


def run_step(
    connection: Any,
    namespace: Namespace,
    *,
    season: int | None = None,
    week: int | None = None,
    season_type: str | None = None,
) -> list[dict[str, Any]]:
    """Run `REFRESH_MODEL` on its own (run id NULL, kind `MODEL` lock); returns its result rows."""
    statement = connection.execute(
        step_call(namespace, season=season, week=week, season_type=season_type)
    )
    return [dict(zip(RESULT_COLUMNS, row, strict=True)) for row in statement.fetchall()]


def step_registered(connection: Any, namespace: Namespace) -> bool:
    """Whether `<meta>.REFRESH_STEPS` registers `REFRESH_MODEL`, so `REFRESH_WEEK` runs it."""
    script = f"{namespace.infra_schema}.{STEP_NAME}"
    rows = connection.execute(
        f"SELECT COUNT(*) FROM {qualified_name(namespace.meta_schema, 'REFRESH_STEPS')} "
        f'WHERE "SCRIPT_NAME" = {string_literal(script)}'
    ).fetchall()
    return int(rows[0][0]) > 0


def rebuild_after_load(
    connection: Any,
    namespace: Namespace,
    log: Callable[[str], None],
    *,
    unless_registered: bool = False,
) -> bool:
    """Post-hook of `make backfill` and `make restore`: rebuild the derived tables (no checks).

    `unless_registered` (`make refresh`): nothing to do when `REFRESH_WEEK` already ran the step
    (step 100 is registered; a target gets it with its next `make deploy`). Says so and returns
    False when the step is not installed or fails; the load itself stays done.
    """
    try:
        if unless_registered and step_registered(connection, namespace):
            return True
        if not step_installed(connection, namespace):
            log(
                f"model: {namespace.infra_schema}.{STEP_NAME} is not installed; run `make model` "
                "to build the derived tables"
            )
            return False
        rows = run_step(connection, namespace)
    except Exception as error:
        message = str(getattr(error, "message", error)).strip().splitlines()
        log(
            f"warning: the model rebuild failed ({message[0] if message else type(error).__name__}"
            f"); the derived tables of {namespace.model_schema} are stale until "
            "`make model-refresh` or the next refresh"
        )
        return False
    tables = [row for row in rows if row["ITEM_KIND"] == "TABLE"]
    total = sum(int(row["OBSERVED"] or 0) for row in tables)
    log(f"model: rebuilt {len(tables)} derived tables of {namespace.model_schema} ({total:,} rows)")
    return True


def write_bundle(out_dir: Path, objects: Sequence[SqlObject], namespace: Namespace) -> Path:
    """Write the step script of `namespace` to `<out_dir>/model_refresh_model.sql`."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / BUNDLE_FILE
    path.write_bytes(build_step_script(namespace, objects).encode("utf-8"))
    return path


def main() -> int:
    from model.deploy import prepare

    namespace = Namespace()
    try:
        path = write_bundle(lua_bundle.DEFAULT_OUT_DIR, prepare(namespace), namespace)
    except (DeployError, OSError) as error:
        print(f"model bundle failed: {error}", file=sys.stderr)
        return 2
    print(f"wrote {path} ({len(path.read_text(encoding='utf-8')):,} characters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
