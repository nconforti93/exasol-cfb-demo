CREATE OR REPLACE FORCE VIEW {MODEL_SCHEMA}.GAME (
  GAME_ID COMMENT IS 'CFBD game id',
  SEASON  COMMENT IS 'Season of the game'
) AS
SELECT g."ID", g."SEASON"
  FROM {CORE_SCHEMA}."GAMES" g
  JOIN {META_SCHEMA}."LOAD_SLICES" s ON s."TABLE_NAME" = 'GAMES'
 WHERE EXTRACT(YEAR FROM g."START_DATE") > 1868
COMMENT IS 'One row per game (deduplicated by game id).';
