-- One row per loader run (BACKFILL, REFRESH_WEEK, SNAPSHOT, RESTORE); the RUNNING row is the run lock.
-- Rendered by vs/host/metaddl.py: {META_SCHEMA} becomes CFB_META, or TEST_CFB_META in the test namespace.
-- Timestamps are UTC. REMAINING_BEFORE and REMAINING_AFTER are the key's remaining calls from /info.

CREATE TABLE {META_SCHEMA}.LOAD_RUN (
  RUN_ID DECIMAL(18,0) IDENTITY NOT NULL,
  RUN_KIND VARCHAR(16) UTF8 NOT NULL,
  RUN_ARGS VARCHAR(200) UTF8,
  SESSION_ID DECIMAL(20,0) NOT NULL,
  STARTED_AT TIMESTAMP NOT NULL,
  ENDED_AT TIMESTAMP,
  RUN_STATUS VARCHAR(20) UTF8 NOT NULL,
  SLICES DECIMAL(9,0),
  ROWS_LOADED DECIMAL(18,0),
  CALLS DECIMAL(9,0),
  REMAINING_BEFORE DECIMAL(9,0),
  REMAINING_AFTER DECIMAL(9,0),
  DETAIL VARCHAR(2000) UTF8
);
