-- Which slices of which tables are stored in CFB_CORE, and whether they are final.
-- Rendered by vs/host/metaddl.py: {META_SCHEMA} becomes CFB_META, or TEST_CFB_META in the test namespace.

CREATE TABLE {META_SCHEMA}.LOAD_LOG (
  TABLE_NAME VARCHAR(128) UTF8 NOT NULL,
  SLICE_KEY VARCHAR(2000) UTF8 NOT NULL,
  IS_FINAL BOOLEAN NOT NULL,
  ROWS_LOADED DECIMAL(18,0) NOT NULL,
  LOADED_AT TIMESTAMP NOT NULL,
  LOADED_BY VARCHAR(64) UTF8 NOT NULL,
  CONSTRAINT LOAD_LOG_PK PRIMARY KEY (TABLE_NAME, SLICE_KEY)
);
