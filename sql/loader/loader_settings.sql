-- LOADER_SETTINGS: one row with the loader's clock and settings. The other loader views and the Lua
-- scripts read "now" from here, so it is one expression everywhere (probe 1.1l).
-- CLOCK_UTC: the statement's time in UTC, CONVERT_TZ of CURRENT_TIMESTAMP from the session time zone
--   (Personal runs in CET; SYSTIMESTAMP would shift twice). Use it for run and step times.
-- NOW_UTC: the clock of the date rules: NOW_OVERRIDE (the test clock, 'YYYY-MM-DD' or
--   'YYYY-MM-DD HH:MM:SS'; deploy keeps it only in TEST_ namespaces), else CLOCK_UTC.
-- CURRENT_SEASON: the year of NOW_UTC from its SEASON_ROLLOVER day (MM-DD) on, the year before until
--   then. MM-DD days compare as text, so a 02-29 setting means 03-01 in a non-leap year.
-- API_FEATURES: the virtual schema property that gates tables, without blanks; NULL means none.
-- A missing setting is NULL and the views fail closed: no current season, nothing final by date,
-- nothing quarantined, nothing spendable.
-- Rendered by vs/host/metaddl.py (render_loader_view): {META_SCHEMA} and {VS_NAME} per namespace.

CREATE OR REPLACE VIEW "{META_SCHEMA}"."LOADER_SETTINGS" AS
WITH CONFIG_VALUES AS (
  SELECT
    MAX(CASE WHEN C."SETTING_NAME" = 'NOW_OVERRIDE' THEN C."SETTING_VALUE" END) AS "NOW_OVERRIDE",
    MAX(CASE WHEN C."SETTING_NAME" = 'SEASON_ROLLOVER' THEN C."SETTING_VALUE" END) AS "SEASON_ROLLOVER",
    MAX(CASE WHEN C."SETTING_NAME" = 'SEASON_FINAL_AFTER' THEN C."SETTING_VALUE" END) AS "SEASON_FINAL_AFTER",
    MAX(CASE WHEN C."SETTING_NAME" = 'QUARANTINE_AFTER' THEN C."SETTING_VALUE" END) AS "QUARANTINE_AFTER",
    MAX(CASE WHEN C."SETTING_NAME" = 'MONTHLY_CALL_BUDGET' THEN C."SETTING_VALUE" END) AS "MONTHLY_CALL_BUDGET",
    MAX(CASE WHEN C."SETTING_NAME" = 'REFRESH_RESERVE' THEN C."SETTING_VALUE" END) AS "REFRESH_RESERVE",
    MAX(CASE WHEN C."SETTING_NAME" = 'REFRESH_PROFILES' THEN C."SETTING_VALUE" END) AS "REFRESH_PROFILES"
  FROM "{META_SCHEMA}"."LOADER_CONFIG" C
),
CLOCKS AS (
  SELECT
    V."SEASON_ROLLOVER" AS "SEASON_ROLLOVER",
    V."SEASON_FINAL_AFTER" AS "SEASON_FINAL_AFTER",
    V."QUARANTINE_AFTER" AS "QUARANTINE_AFTER",
    V."MONTHLY_CALL_BUDGET" AS "MONTHLY_CALL_BUDGET",
    V."REFRESH_RESERVE" AS "REFRESH_RESERVE",
    V."REFRESH_PROFILES" AS "REFRESH_PROFILES",
    CASE
      WHEN LENGTH(V."NOW_OVERRIDE") = 10 THEN TO_TIMESTAMP(V."NOW_OVERRIDE", 'YYYY-MM-DD')
      ELSE TO_TIMESTAMP(V."NOW_OVERRIDE", 'YYYY-MM-DD HH24:MI:SS')
    END AS "OVERRIDE_UTC",
    CONVERT_TZ(CURRENT_TIMESTAMP, SESSIONTIMEZONE, 'UTC') AS "CLOCK_UTC"
  FROM CONFIG_VALUES V
),
EFFECTIVE AS (
  SELECT
    K."CLOCK_UTC" AS "CLOCK_UTC",
    CAST(COALESCE(K."OVERRIDE_UTC", K."CLOCK_UTC") AS TIMESTAMP) AS "NOW_UTC",
    K."SEASON_ROLLOVER" AS "SEASON_ROLLOVER",
    K."SEASON_FINAL_AFTER" AS "SEASON_FINAL_AFTER",
    K."QUARANTINE_AFTER" AS "QUARANTINE_AFTER",
    K."MONTHLY_CALL_BUDGET" AS "MONTHLY_CALL_BUDGET",
    K."REFRESH_RESERVE" AS "REFRESH_RESERVE",
    K."REFRESH_PROFILES" AS "REFRESH_PROFILES"
  FROM CLOCKS K
),
VS_FEATURES AS (
  SELECT
    MAX(REPLACE(X."PROPERTY_VALUE", ' ', '')) AS "API_FEATURES"
  FROM "SYS"."EXA_ALL_VIRTUAL_SCHEMA_PROPERTIES" X
  WHERE X."SCHEMA_NAME" = '{VS_NAME}'
    AND X."PROPERTY_NAME" = 'API_FEATURES'
)
SELECT
  E."CLOCK_UTC" AS "CLOCK_UTC",
  E."NOW_UTC" AS "NOW_UTC",
  CAST(
    CASE
      WHEN TO_CHAR(E."NOW_UTC", 'MM-DD') >= E."SEASON_ROLLOVER" THEN YEAR(E."NOW_UTC")
      WHEN TO_CHAR(E."NOW_UTC", 'MM-DD') < E."SEASON_ROLLOVER" THEN YEAR(E."NOW_UTC") - 1
    END AS DECIMAL(4,0)
  ) AS "CURRENT_SEASON",
  E."SEASON_ROLLOVER" AS "SEASON_ROLLOVER",
  E."SEASON_FINAL_AFTER" AS "SEASON_FINAL_AFTER",
  CAST(E."QUARANTINE_AFTER" AS DECIMAL(9,0)) AS "QUARANTINE_AFTER",
  CAST(E."MONTHLY_CALL_BUDGET" AS DECIMAL(9,0)) AS "MONTHLY_CALL_BUDGET",
  CAST(E."REFRESH_RESERVE" AS DECIMAL(9,0)) AS "REFRESH_RESERVE",
  E."REFRESH_PROFILES" AS "REFRESH_PROFILES",
  F."API_FEATURES" AS "API_FEATURES"
FROM EFFECTIVE E
CROSS JOIN VS_FEATURES F
