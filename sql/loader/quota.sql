-- QUOTA: one row with the key's monthly quota, the project budget and what may be spent (spec
-- loader/quota). It reads /info through the virtual schema exactly once per query; /info costs no
-- call. If /info returns no row, the view has no row: the scripts treat that as "quota unreadable".
-- USED_CALLS counts every call of the key this month (other tools and the shared pool too), so
-- PROJECT_BUDGET caps the key's whole monthly use, for every SQL client:
--   PROJECT_BUDGET     = LEAST(MONTHLY_LIMIT, MONTHLY_CALL_BUDGET)
--   REFRESH_SPENDABLE  = GREATEST(0, LEAST(REMAINING_CALLS, PROJECT_BUDGET - USED_CALLS))
--   BACKFILL_SPENDABLE = GREATEST(0, REFRESH_SPENDABLE - REFRESH_RESERVE)
-- Both spendable amounts are 0, never NULL, when a setting or an /info value is missing.
-- RESET_AT is /info's resetAt as a UTC TIMESTAMP; PERIOD_START = ADD_MONTHS(RESET_AT, -1).
-- BACKFILL_CALLS, REFRESH_CALLS: HTTP attempts of LIVE FETCH_LOG rows in [PERIOD_START, RESET_AT)
-- (request time, else log time) whose CONTEXT is 'BACKFILL#<run>' or 'REFRESH_WEEK#<run>'.
-- Attempts, not rows: retries count against the key like first tries do.
-- OTHER_CALLS = GREATEST(0, USED_CALLS - BACKFILL_CALLS - REFRESH_CALLS): on-demand queries, other
-- clients, failed batches (rolled back, so not logged) and the shared pool.
-- DEMO_CALLS_TO_COMPLETE, FULL_CALLS_TO_COMPLETE: pending slices (LOAD_SLICES.IS_PENDING) of the demo
-- profile, and of demo plus full; gaps and quarantined slices excluded, tables with orphans included.
-- Rendered by vs/host/metaddl.py (render_loader_view): {VS_NAME}.INFO is the namespace's /info table.

CREATE OR REPLACE VIEW "{META_SCHEMA}"."QUOTA" AS
WITH KEY_INFO AS (
  SELECT
    I."TIER_NAME" AS "TIER_NAME",
    CAST(I."MONTHLY_LIMIT" AS DECIMAL(18,0)) AS "MONTHLY_LIMIT",
    CAST(I."USED_CALLS" AS DECIMAL(18,0)) AS "USED_CALLS",
    CAST(I."REMAINING_CALLS" AS DECIMAL(18,0)) AS "REMAINING_CALLS",
    CAST(
      TO_TIMESTAMP(REPLACE(SUBSTR(I."RESET_AT", 1, 19), 'T', ' '), 'YYYY-MM-DD HH24:MI:SS')
      AS TIMESTAMP
    ) AS "RESET_AT"
  FROM "{VS_NAME}"."INFO" I
),
RUN_FETCHES AS (
  SELECT
    COALESCE(F."REQUESTED_AT", F."LOGGED_AT") AS "FETCHED_AT",
    CASE WHEN SUBSTR(F."CONTEXT", 1, 9) = 'BACKFILL#' THEN 'BACKFILL' ELSE 'REFRESH_WEEK' END
      AS "RUN_KIND",
    GREATEST(COALESCE(F."ATTEMPTS", 1), 1) AS "CALLS"
  FROM "{META_SCHEMA}"."FETCH_LOG" F
  WHERE F."REQ_SOURCE" = 'LIVE'
    AND (
      SUBSTR(F."CONTEXT", 1, 9) = 'BACKFILL#'
      OR SUBSTR(F."CONTEXT", 1, 13) = 'REFRESH_WEEK#'
    )
),
PERIOD_USE AS (
  SELECT
    K."TIER_NAME" AS "TIER_NAME",
    K."MONTHLY_LIMIT" AS "MONTHLY_LIMIT",
    K."USED_CALLS" AS "USED_CALLS",
    K."REMAINING_CALLS" AS "REMAINING_CALLS",
    K."RESET_AT" AS "RESET_AT",
    ADD_MONTHS(K."RESET_AT", -1) AS "PERIOD_START",
    SUM(CASE WHEN R."RUN_KIND" = 'BACKFILL' THEN R."CALLS" ELSE 0 END) AS "BACKFILL_CALLS",
    SUM(CASE WHEN R."RUN_KIND" = 'REFRESH_WEEK' THEN R."CALLS" ELSE 0 END) AS "REFRESH_CALLS"
  FROM KEY_INFO K
  LEFT JOIN RUN_FETCHES R
    ON R."FETCHED_AT" >= ADD_MONTHS(K."RESET_AT", -1)
    AND R."FETCHED_AT" < K."RESET_AT"
  GROUP BY K."TIER_NAME", K."MONTHLY_LIMIT", K."USED_CALLS", K."REMAINING_CALLS", K."RESET_AT"
),
BUDGET AS (
  SELECT
    U."TIER_NAME" AS "TIER_NAME",
    U."MONTHLY_LIMIT" AS "MONTHLY_LIMIT",
    U."USED_CALLS" AS "USED_CALLS",
    U."REMAINING_CALLS" AS "REMAINING_CALLS",
    U."RESET_AT" AS "RESET_AT",
    U."PERIOD_START" AS "PERIOD_START",
    CFG."MONTHLY_CALL_BUDGET" AS "MONTHLY_CALL_BUDGET",
    CFG."REFRESH_RESERVE" AS "REFRESH_RESERVE",
    LEAST(U."MONTHLY_LIMIT", CFG."MONTHLY_CALL_BUDGET") AS "PROJECT_BUDGET",
    U."BACKFILL_CALLS" AS "BACKFILL_CALLS",
    U."REFRESH_CALLS" AS "REFRESH_CALLS"
  FROM PERIOD_USE U
  CROSS JOIN "{META_SCHEMA}"."LOADER_SETTINGS" CFG
),
SPENDABLE AS (
  SELECT
    B."TIER_NAME" AS "TIER_NAME",
    B."MONTHLY_LIMIT" AS "MONTHLY_LIMIT",
    B."USED_CALLS" AS "USED_CALLS",
    B."REMAINING_CALLS" AS "REMAINING_CALLS",
    B."RESET_AT" AS "RESET_AT",
    B."PERIOD_START" AS "PERIOD_START",
    B."MONTHLY_CALL_BUDGET" AS "MONTHLY_CALL_BUDGET",
    B."REFRESH_RESERVE" AS "REFRESH_RESERVE",
    B."PROJECT_BUDGET" AS "PROJECT_BUDGET",
    COALESCE(GREATEST(0, LEAST(B."REMAINING_CALLS", B."PROJECT_BUDGET" - B."USED_CALLS")), 0)
      AS "REFRESH_SPENDABLE",
    B."BACKFILL_CALLS" AS "BACKFILL_CALLS",
    B."REFRESH_CALLS" AS "REFRESH_CALLS"
  FROM BUDGET B
),
PENDING AS (
  SELECT
    SUM(CASE WHEN S."IS_PENDING" AND S."PROFILE_NAME" = 'demo' THEN 1 ELSE 0 END)
      AS "DEMO_PENDING",
    SUM(CASE WHEN S."IS_PENDING" AND S."PROFILE_NAME" IN ('demo', 'full') THEN 1 ELSE 0 END)
      AS "FULL_PENDING"
  FROM "{META_SCHEMA}"."LOAD_SLICES" S
)
SELECT
  SP."TIER_NAME" AS "TIER_NAME",
  SP."MONTHLY_LIMIT" AS "MONTHLY_LIMIT",
  SP."USED_CALLS" AS "USED_CALLS",
  SP."REMAINING_CALLS" AS "REMAINING_CALLS",
  SP."RESET_AT" AS "RESET_AT",
  SP."PERIOD_START" AS "PERIOD_START",
  SP."MONTHLY_CALL_BUDGET" AS "MONTHLY_CALL_BUDGET",
  SP."REFRESH_RESERVE" AS "REFRESH_RESERVE",
  CAST(SP."PROJECT_BUDGET" AS DECIMAL(18,0)) AS "PROJECT_BUDGET",
  CAST(SP."REFRESH_SPENDABLE" AS DECIMAL(18,0)) AS "REFRESH_SPENDABLE",
  CAST(COALESCE(GREATEST(0, SP."REFRESH_SPENDABLE" - SP."REFRESH_RESERVE"), 0) AS DECIMAL(18,0))
    AS "BACKFILL_SPENDABLE",
  CAST(SP."BACKFILL_CALLS" AS DECIMAL(18,0)) AS "BACKFILL_CALLS",
  CAST(SP."REFRESH_CALLS" AS DECIMAL(18,0)) AS "REFRESH_CALLS",
  CAST(GREATEST(0, SP."USED_CALLS" - SP."BACKFILL_CALLS" - SP."REFRESH_CALLS") AS DECIMAL(18,0))
    AS "OTHER_CALLS",
  CAST(COALESCE(PD."DEMO_PENDING", 0) AS DECIMAL(18,0)) AS "DEMO_CALLS_TO_COMPLETE",
  CAST(COALESCE(PD."FULL_PENDING", 0) AS DECIMAL(18,0)) AS "FULL_CALLS_TO_COMPLETE"
FROM SPENDABLE SP
CROSS JOIN PENDING PD
