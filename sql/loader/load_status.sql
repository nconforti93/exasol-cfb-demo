-- LOAD_STATUS: one row per LOAD_PLAN entry, also a gated one (spec loader/load-plan).
-- Counts over the entry's LOAD_SLICES rows:
--   SLICES_PLANNED all, GAP_SLICES gaps, SLICES_STORED with a LOAD_LOG row (registered gaps too),
--   SLICES_FINAL stored and final, SLICES_MISSING without a LOAD_LOG row and not a gap (quarantined
--   ones included), QUARANTINED_SLICES, CALLS_TO_COMPLETE the pending slices (IS_PENDING: gaps and
--   quarantined slices cost nothing), STORED_ROWS and LAST_LOADED_AT of the stored slices.
-- ORPHAN_SLICES: orphans of the entry's table (LOAD_ORPHANS); a table's count repeats on each of its
--   entries, because the loader refuses the whole table.
-- CALLS_TO_COMPLETE also counts tables blocked by orphans: the calls are still needed once the
--   orphans are resolved. BACKFILL_QUEUE leaves those tables out.
-- BLOCKED_BY: the missing API feature (e.g. 'weather'; the entry then has no slices), else 'ORPHANS'
--   when its table has orphans, else NULL.
-- LAST_ERROR_SLICE, LAST_ERROR: the failing slice to show, quarantined ones first, then the latest.
-- Rendered by vs/host/metaddl.py (render_loader_view).

CREATE OR REPLACE VIEW "{META_SCHEMA}"."LOAD_STATUS" AS
WITH SLICE_COUNTS AS (
  SELECT
    S."ENTRY_ID" AS "ENTRY_ID",
    COUNT(*) AS "SLICES_PLANNED",
    SUM(CASE WHEN S."IS_GAP" THEN 1 ELSE 0 END) AS "GAP_SLICES",
    SUM(CASE WHEN S."IS_STORED" THEN 1 ELSE 0 END) AS "SLICES_STORED",
    SUM(CASE WHEN S."IS_STORED" AND S."IS_FINAL" THEN 1 ELSE 0 END) AS "SLICES_FINAL",
    SUM(CASE WHEN NOT S."IS_STORED" AND NOT S."IS_GAP" THEN 1 ELSE 0 END) AS "SLICES_MISSING",
    SUM(CASE WHEN S."IS_QUARANTINED" THEN 1 ELSE 0 END) AS "QUARANTINED_SLICES",
    SUM(CASE WHEN S."IS_PENDING" THEN 1 ELSE 0 END) AS "CALLS_TO_COMPLETE",
    SUM(S."ROWS_LOADED") AS "STORED_ROWS",
    MAX(S."LOADED_AT") AS "LAST_LOADED_AT"
  FROM "{META_SCHEMA}"."LOAD_SLICES" S
  GROUP BY S."ENTRY_ID"
),
ORPHAN_COUNTS AS (
  SELECT
    O."TABLE_NAME" AS "TABLE_NAME",
    COUNT(*) AS "ORPHAN_SLICES"
  FROM "{META_SCHEMA}"."LOAD_ORPHANS" O
  GROUP BY O."TABLE_NAME"
),
FAILING AS (
  SELECT
    F."ENTRY_ID" AS "ENTRY_ID",
    F."SLICE_KEY" AS "SLICE_KEY",
    F."LAST_ERROR" AS "LAST_ERROR",
    ROW_NUMBER() OVER (
      PARTITION BY F."ENTRY_ID"
      ORDER BY
        CASE WHEN F."IS_QUARANTINED" THEN 0 ELSE 1 END,
        F."LAST_FAILED_AT" DESC NULLS LAST,
        F."SLICE_KEY"
    ) AS "ERROR_RANK"
  FROM "{META_SCHEMA}"."LOAD_SLICES" F
  WHERE F."FAILURES" > 0
)
SELECT
  P."ENTRY_ID" AS "ENTRY_ID",
  P."TABLE_NAME" AS "TABLE_NAME",
  P."PROFILE_NAME" AS "PROFILE_NAME",
  P."PROFILE_RANK" AS "PROFILE_RANK",
  P."PRIORITY" AS "PRIORITY",
  P."SLICING" AS "SLICING",
  P."REFRESH_CLASS" AS "REFRESH_CLASS",
  P."SEASON_FROM" AS "SEASON_FROM",
  P."SEASON_TO" AS "SEASON_TO",
  P."GATED_BY" AS "GATED_BY",
  CAST(COALESCE(C."SLICES_PLANNED", 0) AS DECIMAL(18,0)) AS "SLICES_PLANNED",
  CAST(COALESCE(C."GAP_SLICES", 0) AS DECIMAL(18,0)) AS "GAP_SLICES",
  CAST(COALESCE(C."SLICES_STORED", 0) AS DECIMAL(18,0)) AS "SLICES_STORED",
  CAST(COALESCE(C."SLICES_FINAL", 0) AS DECIMAL(18,0)) AS "SLICES_FINAL",
  CAST(COALESCE(C."SLICES_MISSING", 0) AS DECIMAL(18,0)) AS "SLICES_MISSING",
  CAST(COALESCE(C."QUARANTINED_SLICES", 0) AS DECIMAL(18,0)) AS "QUARANTINED_SLICES",
  CAST(COALESCE(OC."ORPHAN_SLICES", 0) AS DECIMAL(18,0)) AS "ORPHAN_SLICES",
  CAST(COALESCE(C."CALLS_TO_COMPLETE", 0) AS DECIMAL(18,0)) AS "CALLS_TO_COMPLETE",
  CAST(COALESCE(C."STORED_ROWS", 0) AS DECIMAL(18,0)) AS "STORED_ROWS",
  C."LAST_LOADED_AT" AS "LAST_LOADED_AT",
  CASE
    WHEN P."GATED_BY" IS NOT NULL
      AND INSTR(',' || CFG."API_FEATURES" || ',', ',' || P."GATED_BY" || ',') = 0 THEN P."GATED_BY"
    WHEN OC."ORPHAN_SLICES" > 0 THEN 'ORPHANS'
  END AS "BLOCKED_BY",
  FE."SLICE_KEY" AS "LAST_ERROR_SLICE",
  FE."LAST_ERROR" AS "LAST_ERROR"
FROM "{META_SCHEMA}"."LOAD_PLAN" P
CROSS JOIN "{META_SCHEMA}"."LOADER_SETTINGS" CFG
LEFT JOIN SLICE_COUNTS C
  ON C."ENTRY_ID" = P."ENTRY_ID"
LEFT JOIN ORPHAN_COUNTS OC
  ON OC."TABLE_NAME" = P."TABLE_NAME"
LEFT JOIN FAILING FE
  ON FE."ENTRY_ID" = P."ENTRY_ID"
  AND FE."ERROR_RANK" = 1
