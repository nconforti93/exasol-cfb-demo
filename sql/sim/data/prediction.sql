-- Frozen score-model forecast. This data table survives every simulation deploy.
CREATE TABLE IF NOT EXISTS {SIM_SCHEMA}.PREDICTION (
  GAME_ID DECIMAL(18,0) NOT NULL COMMENT IS 'CFBD game id, unique in this table',
  SEASON DECIMAL(4,0) NOT NULL COMMENT IS 'Season of the predicted game',
  SEASON_TYPE VARCHAR(10) UTF8 NOT NULL COMMENT IS 'Regular or postseason game',
  WEEK DECIMAL(3,0) NOT NULL COMMENT IS 'Game week within its season type at the freeze',
  WEEK_SEQ DECIMAL(3,0) NOT NULL COMMENT IS 'Game week sequence at the freeze',
  START_AT TIMESTAMP COMMENT IS 'Kickoff as known at the freeze, UTC',
  HOME_TEAM_ID DECIMAL(18,0) NOT NULL COMMENT IS 'Home team id at the freeze',
  AWAY_TEAM_ID DECIMAL(18,0) NOT NULL COMMENT IS 'Away team id at the freeze',
  IS_NEUTRAL_SITE BOOLEAN COMMENT IS 'Neutral-site flag at the freeze',
  IS_CONF_CHAMPIONSHIP BOOLEAN COMMENT IS 'Conference championship flag at the freeze',
  IS_FBS_VS_FBS BOOLEAN NOT NULL COMMENT IS 'Both teams classified FBS at the freeze',
  FREEZE_SEASON DECIMAL(4,0) NOT NULL COMMENT IS 'Season of the as-of point used for the score model',
  FREEZE_WEEK_SEQ DECIMAL(3,0) NOT NULL COMMENT IS 'Week sequence of the as-of point used for the score model',
  FREEZE_LABEL VARCHAR(100) UTF8 COMMENT IS 'Display label of the as-of point',
  HOME_RATING DECIMAL(7,2) COMMENT IS 'Home team rating at the freeze',
  AWAY_RATING DECIMAL(7,2) COMMENT IS 'Away team rating at the freeze',
  HOME_RATING_SOURCE VARCHAR(16) ASCII COMMENT IS 'Source of the home team rating',
  AWAY_RATING_SOURCE VARCHAR(16) ASCII COMMENT IS 'Source of the away team rating',
  MU DECIMAL(7,2) NOT NULL COMMENT IS 'Expected home margin at the freeze',
  SIGMA DECIMAL(5,2) NOT NULL COMMENT IS 'Standard deviation of the margin at the freeze',
  TOTAL DECIMAL(5,1) COMMENT IS 'Predicted combined points at the freeze',
  HOME_POINTS_PRED DECIMAL(5,1) COMMENT IS 'Predicted home points at the freeze',
  AWAY_POINTS_PRED DECIMAL(5,1) COMMENT IS 'Predicted away points at the freeze',
  HOME_WIN_PROB DECIMAL(5,4) NOT NULL COMMENT IS 'Frozen probability of a home win',
  PICK_TEAM_ID DECIMAL(18,0) NOT NULL COMMENT IS 'Team selected by the frozen prediction',
  PICK_WIN_PROB DECIMAL(5,4) NOT NULL COMMENT IS 'Frozen probability that the selected team wins',
  FROZEN_AT TIMESTAMP NOT NULL COMMENT IS 'Loader clock in UTC when the prediction was inserted',
  FROZEN_BEFORE_KICKOFF BOOLEAN NOT NULL COMMENT IS 'TRUE only when FROZEN_AT is before START_AT',
  FREEZE_KIND VARCHAR(16) ASCII NOT NULL COMMENT IS 'IN_ADVANCE or RECONSTRUCTED',
  FROZEN_BY VARCHAR(64) UTF8 NOT NULL COMMENT IS 'PREDICT, SIMULATE run id or REFRESH load run id'
) COMMENT IS 'One row per predicted game, frozen once from GAME_SCORE_AS_OF at the previous as-of point. Redeploys and later model fits retain the row.';
