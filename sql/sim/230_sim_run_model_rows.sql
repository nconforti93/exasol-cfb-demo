-- The model rows of a run in the shape of the engine's input (sim-engine/engine-contract): RUN_ID, then
-- exactly the columns of engine.core.MODEL_COLUMNS, with their types. One TEAM row per snapshot team, one
-- GAME row per snapshot game (REMAINING and PLAYED_CONF), one PARAM row per run parameter; the columns of
-- the other kinds are NULL. SIMULATE calls the engine over these rows of one run, cross-joined with the
-- batch ids and grouped by batch, so every engine call reads the run's whole snapshot.
CREATE OR REPLACE FORCE VIEW {SIM_SCHEMA}.SIM_RUN_MODEL_ROWS (
  RUN_ID      COMMENT IS 'The run whose snapshot the row comes from',
  ROW_KIND    COMMENT IS 'TEAM, GAME or PARAM: which snapshot table the row comes from',
  GAME_ROLE   COMMENT IS 'GAME rows: REMAINING (simulated) or PLAYED_CONF (head-to-head only); NULL otherwise',
  TEAM_IDX    COMMENT IS 'TEAM rows: the team''s position in the engine input, 0 upwards by team id; NULL otherwise',
  TEAM_ID     COMMENT IS 'TEAM rows: CFBD team id; NULL otherwise',
  CONFERENCE  COMMENT IS 'TEAM rows: conference of a P4 or G6 team; NULL for independents, non-FBS teams and other kinds',
  TIER        COMMENT IS 'TEAM rows: P4, G6, IND or NON_FBS; NULL otherwise',
  HAS_CCG     COMMENT IS 'TEAM rows: TRUE when the team''s conference plays a championship game; NULL otherwise',
  IS_ELIGIBLE COMMENT IS 'TEAM rows: TRUE when the team can be selected for the playoff; NULL otherwise',
  RATING      COMMENT IS 'TEAM rows: rating in points against an average FBS team; NULL otherwise',
  SOS         COMMENT IS 'TEAM rows: strength of schedule, the mean rating of the opponents; NULL otherwise',
  WINS        COMMENT IS 'TEAM rows: wins so far; NULL otherwise',
  LOSSES      COMMENT IS 'TEAM rows: losses so far; NULL otherwise',
  CONF_WINS   COMMENT IS 'TEAM rows: conference wins so far; NULL otherwise',
  CONF_LOSSES COMMENT IS 'TEAM rows: conference losses so far; NULL otherwise',
  CONF_PD     COMMENT IS 'TEAM rows: conference point differential so far; NULL otherwise',
  CAPPED_PD   COMMENT IS 'TEAM rows: point differential so far with each margin capped; NULL otherwise',
  GAME_IDX    COMMENT IS 'GAME rows: position among the games of the role, 0 upwards; for REMAINING games the outcome string position minus 1; NULL otherwise',
  HOME_IDX    COMMENT IS 'GAME rows: TEAM_IDX of the home team; NULL otherwise',
  AWAY_IDX    COMMENT IS 'GAME rows: TEAM_IDX of the away team; NULL otherwise',
  CONF_GAME   COMMENT IS 'GAME rows: TRUE for a conference game between two teams of one conference; NULL otherwise',
  MU          COMMENT IS 'REMAINING rows: expected home margin in points; NULL otherwise',
  TEAM_SIGMA  COMMENT IS 'REMAINING rows: scale in points of the shared team-strength offsets; NULL otherwise',
  MARGIN      COMMENT IS 'PLAYED_CONF rows: final home margin; NULL otherwise',
  PARAM_KEY   COMMENT IS 'PARAM rows: the engine''s lower-case parameter name; NULL otherwise',
  PARAM_VALUE COMMENT IS 'PARAM rows: the parameter value; NULL otherwise'
) AS
SELECT t."RUN_ID",
       CAST('TEAM' AS VARCHAR(5) ASCII),
       CAST(NULL AS VARCHAR(12) ASCII),
       CAST(t."TEAM_IDX" AS DECIMAL(5,0)),
       CAST(t."TEAM_ID" AS DECIMAL(18,0)),
       CAST(t."CONFERENCE" AS VARCHAR(100) UTF8),
       CAST(t."TIER" AS VARCHAR(8) ASCII),
       t."HAS_CCG",
       t."IS_ELIGIBLE",
       CAST(t."RATING" AS DECIMAL(6,2)),
       CAST(t."SOS" AS DECIMAL(6,2)),
       CAST(t."WINS" AS DECIMAL(2,0)),
       CAST(t."LOSSES" AS DECIMAL(2,0)),
       CAST(t."CONF_WINS" AS DECIMAL(2,0)),
       CAST(t."CONF_LOSSES" AS DECIMAL(2,0)),
       CAST(t."CONF_PD" AS DECIMAL(5,0)),
       CAST(t."CAPPED_PD" AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS DECIMAL(7,2)),
       CAST(NULL AS DECIMAL(5,2)),
       CAST(NULL AS DECIMAL(4,0)),
       CAST(NULL AS VARCHAR(40) ASCII),
       CAST(NULL AS DECIMAL(12,4))
  FROM {SIM_SCHEMA}.SIM_RUN_TEAM t
UNION ALL
SELECT g."RUN_ID",
       CAST('GAME' AS VARCHAR(5) ASCII),
       CAST(g."GAME_ROLE" AS VARCHAR(12) ASCII),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(18,0)),
       CAST(NULL AS VARCHAR(100) UTF8),
       CAST(NULL AS VARCHAR(8) ASCII),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS DECIMAL(6,2)),
       CAST(NULL AS DECIMAL(6,2)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(g."GAME_IDX" AS DECIMAL(5,0)),
       CAST(g."HOME_IDX" AS DECIMAL(5,0)),
       CAST(g."AWAY_IDX" AS DECIMAL(5,0)),
       g."CONF_GAME",
       CAST(g."MU" AS DECIMAL(7,2)),
       CAST(g."TEAM_SIGMA" AS DECIMAL(5,2)),
       CAST(g."MARGIN" AS DECIMAL(4,0)),
       CAST(NULL AS VARCHAR(40) ASCII),
       CAST(NULL AS DECIMAL(12,4))
  FROM {SIM_SCHEMA}.SIM_RUN_GAME g
UNION ALL
SELECT p."RUN_ID",
       CAST('PARAM' AS VARCHAR(5) ASCII),
       CAST(NULL AS VARCHAR(12) ASCII),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(18,0)),
       CAST(NULL AS VARCHAR(100) UTF8),
       CAST(NULL AS VARCHAR(8) ASCII),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS DECIMAL(6,2)),
       CAST(NULL AS DECIMAL(6,2)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(2,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS DECIMAL(5,0)),
       CAST(NULL AS BOOLEAN),
       CAST(NULL AS DECIMAL(7,2)),
       CAST(NULL AS DECIMAL(5,2)),
       CAST(NULL AS DECIMAL(4,0)),
       CAST(p."PARAM_KEY" AS VARCHAR(40) ASCII),
       CAST(p."PARAM_VALUE" AS DECIMAL(12,4))
  FROM {SIM_SCHEMA}.SIM_RUN_PARAM p
COMMENT IS 'One row per run and tagged model row of its input snapshot: a TEAM row per SIM_RUN_TEAM row, a GAME row per SIM_RUN_GAME row and a PARAM row per SIM_RUN_PARAM row, in the column order and types of the engine''s input (CFB_INFRA.SIM_ENGINE after its four run columns). Filter on RUN_ID.';
