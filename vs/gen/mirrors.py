"""CFB_CORE mirror DDL: one `CREATE TABLE` per read-through table, from the catalog (host-side).

A mirror has the column names, order and types of its virtual table, so stored rows and live
rows are interchangeable. The types come from `sqlrender.column_sql_types`, the same function
that types the virtual table's metadata and the fetch UDF's `EMITS` clause, so they are identical
by construction. Output is deterministic: tables sorted by name, no timestamps.
"""

from __future__ import annotations

import re
from collections.abc import Iterable

from vs.cfbd_vs.catalog import Table
from vs.cfbd_vs.sqlrender import RenderError, column_sql_types

CORE_SCHEMA = "CFB_CORE"

_IDENTIFIER = re.compile(r"^[A-Z][A-Z0-9_]*$")


class MirrorError(ValueError):
    """A catalog name cannot be used as an unquoted Exasol identifier."""


def render_mirrors(tables: Iterable[Table], catalog_hash: str, schema: str = CORE_SCHEMA) -> str:
    """Render the DDL of every read-through table, sorted by table name."""
    _check_identifier(schema, "schema")
    mirrored = sorted((t for t in tables if t.read_through), key=lambda t: t.name)
    header = (
        f"-- Mirrors of the read-through tables of CFBD_VS (catalog {catalog_hash}).\n"
        "-- Generated by vs/generate.py. Do not edit.\n"
    )
    return header + "".join("\n" + _create_table(t, schema) for t in mirrored)


def _create_table(table: Table, schema: str) -> str:
    _check_identifier(table.name, "table name")
    for column in table.columns:
        _check_identifier(column.name, f"column name in {table.name}")
    try:
        columns = column_sql_types(table)
    except RenderError as error:
        raise MirrorError(str(error)) from None
    lines = [f"  {name} {sql_type}" for name, sql_type in columns]
    return f"CREATE TABLE {schema}.{table.name} (\n" + ",\n".join(lines) + "\n);\n"


def _check_identifier(name: str, what: str) -> None:
    if not _IDENTIFIER.match(name):
        raise MirrorError(f"{what} {name!r} is not a valid unquoted identifier")
